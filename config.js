// Перевірка нікнейму на мати (укр/рус/англ) та заборонені символи
window.validateNickname = function(rawNick) {
  const nick = (rawNick || '').trim();

  if (nick.length < 2 || nick.length > 15) {
    return { valid: false, error: 'Нік має бути від 2 до 15 символів' };
  }

  // ТІЛЬКИ літери (укр/рус/англ) та цифри — жодних символів, пробілів і підкреслень
  if (!/^[a-zA-Zа-яА-ЯіІїЇєЄґҐ0-9]+$/.test(nick)) {
    return { valid: false, error: 'Тільки літери та цифри (без символів і пробілів)' };
  }

  const BAD_ROOTS = [
    'хуи', 'хуе', 'хуя', 'хул', 'хую',
    'пизд', 'пізд',
    'еба', 'ебл', 'ебу', 'ебн', 'еби', 'ебо', 'ебт', 'ебс',
    'иба', 'ибл', 'ибу', 'ибн', 'иби', 'ибо',
    'уеб', 'уиоб', 'уебищ', 'уиобищ', 'виеб', 'вииоб', 'заеб', 'заиоб', 'поеб', 'поиоб', 'наеб', 'наиоб', 'разъеб', 'розиоб', 'долбоеб', 'довбоиоб', 'довбоеб',
    'бля', 'блє', 'бляд',
    'сук', 'суч',
    'муд', 'мудил', 'мудак',
    'гандон', 'гондон',
    'пидор', 'пидар', 'педик', 'педр',
    'шлюх', 'шалав', 'проститут',
    'залуп', 'дроч', 'сперм', 'анал', 'минет', 'мінет', 'куни', 'куні', 'клитор', 'клітор', 'вагин', 'вагін', 'член', 'пенис', 'пеніс',
    'курв', 'лярв', 'стерв', 'падл', 'покидь', 'вибляд', 'виродок', 'вилупок',
    'говн', 'гівн', 'гивн', 'срак', 'жоп', 'перд', 'сця', 'ссат', 'бзд',
    'даун', 'дебил', 'дебіл', 'имбецил', 'імбецил', 'кретин', 'урод', 'лох', 'чмо', 'лошар',
    'хач', 'чурк', 'жид', 'нигер', 'нігер', 'негр', 'кацап', 'хохол', 'москал',
    'fuck', 'fck', 'fuk', 'shit', 'bitch', 'btch', 'dick', 'cock', 'pussy', 
    'nigg', 'whore', 'slut', 'cunt', 'asshole', 'bastard', 'motherfucker', 'mf', 'retard', 'faggot', 'fag'
  ];

  const map = {
    '0': 'о', '3': 'е', '4': 'ч', '6': 'б', '1': 'и', '7': 'т', '8': 'в',
    'a': 'а', 'b': 'в', 'c': 'с', 'd': 'д', 'e': 'е', 'f': 'ф', 'g': 'г',
    'h': 'н', 'i': 'и', 'j': 'и', 'k': 'к', 'l': 'л', 'm': 'м', 'n': 'н',
    'o': 'о', 'p': 'р', 'r': 'р', 's': 'с', 't': 'т', 'u': 'у', 'v': 'в',
    'w': 'в', 'x': 'х', 'y': 'и', 'z': 'з',
    'і': 'и', 'ї': 'и', 'й': 'и', 'ы': 'и',
    'є': 'е', 'э': 'е', 'ё': 'е', 'ґ': 'г'
  };

  let normalized = nick.toLowerCase()
    .split('')
    .map(ch => map[ch] || ch)
    .join('')
    .replace(/(.)\1+/g, '$1');

  const latinNormalized = nick.toLowerCase().replace(/(.)\1+/g, '$1');

  if (BAD_ROOTS.some(root => normalized.includes(root) || latinNormalized.includes(root))) {
    return { valid: false, error: 'Цей нікнейм заборонено!' };
  }

  return { valid: true, cleanNick: nick };
};
